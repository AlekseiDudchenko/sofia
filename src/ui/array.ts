/** Строй миньонов: 2 × 4 — это два ряда по четыре.
 *
 * Пока факт новый, его не вспоминают, а считают, и считать по картинке
 * честнее, чем по пальцам: количество видно целиком, ряды разложены поровну,
 * и «четыре да ещё четыре» читается прямо с экрана.
 *
 * Строй за кнопкой, а не на виду, и не для всех примеров — иначе тренажёр
 * превратится в счётный прибор, а нужен автоматизм. По той же причине ответ
 * со строем на экране не двигает ступень факта: см. drill.ts.
 */

import { minionHTML, setMinionMood, type MinionMood } from "./minion.js";

/** Докуда рисуем строй.
 *
 * 25 — это вся ×2, вся ×5 и мелочь из ×3 и ×4: ровно те факты, которые ещё
 * считают. Дальше картинка перестаёт работать дважды: 56 миньонов не
 * пересчитать, а чтобы они влезли в экран, их пришлось бы ужать до
 * нечитаемых 17 пикселей. Большие примеры и так учат наизусть. */
export const ARRAY_MAX_PRODUCT = 25;

/** Больше пяти рядов на экране телефона не помещается: строй делит между
 *  рядами то место, что осталось от примера и клавиатуры, и девять рядов по
 *  два — это девять полосок по десять пикселей. */
export const ARRAY_MAX_ROWS = 5;

/** Рисуется ли строй для примера. */
export function hasArray(left: number, right: number): boolean {
    return left * right <= ARRAY_MAX_PRODUCT;
}

/** Как разложить пример в строй.
 *
 * Обычно первое число — это ряды: 2 × 4 — два ряда по четыре. Но девять
 * рядов по два в экран не влезают, поэтому длинный строй кладётся на бок:
 * 9 × 2 показывается тем же строем, что и 2 × 9. Количество от этого не
 * меняется — это и есть переместительный закон, увиденный, а не рассказанный.
 *
 * Разворот всегда даёт не больше пяти рядов: если оба множителя больше пяти,
 * произведение уже за порогом и подсказки нет вовсе. */
export function arrayShape(left: number, right: number): { rows: number; cols: number } {
    return left <= ARRAY_MAX_ROWS ? { rows: left, cols: right } : { rows: right, cols: left };
}

/** Разметка строя: rows рядов по cols миньонов.
 *
 * Порядок тот же, в каком пример стоит на экране: первое число — сколько
 * рядов, второе — сколько в ряду. Перевёрнутый показ (4 × 2 вместо 2 × 4)
 * даёт четыре ряда по два, и это ровно то, что должно быть видно, — та же
 * восьмёрка, положенная на бок.
 *
 * Возвращаются только ряды: контейнер живёт на экране тренировки, потому что
 * высоту строя считает CSS от места, оставшегося под клавиатурой. */
export function arrayHTML(rows: number, cols: number): string {
    let index = 0;
    const lines: string[] = [];

    for (let r = 0; r < rows; r++) {
        const minions: string[] = [];
        for (let c = 0; c < cols; c++, index++) {
            // Глаза чередуются, как в команде на главной: два десятка
            // одинаковых миньонов читаются как обои, а не как строй.
            minions.push(minionHTML({ size: "row", eyes: index % 3 === 1 ? 1 : 2 }));
        }
        lines.push(`<div class="arow">${minions.join("")}</div>`);
    }

    return lines.join("");
}

/** Реакция на ответ у всего строя разом.
 *
 * Маскот на время подсказки уходит — вдвоём со строем им тесно, — и без
 * этого экран отвечал бы на ошибку только цветом поля. Настроение меняют
 * все миньоны: их тут и так столько, сколько в примере. */
export function setArrayMood(scope: HTMLElement, mood: MinionMood): void {
    scope.querySelectorAll<HTMLElement>(".minion").forEach((el) => setMinionMood(el, mood));
}
